# ============================================================
# build.ps1 — RemoteAdminTool Master Build Script
# ============================================================
# Usage:
#   .\build.ps1                                  — patch constants + build all
#   .\build.ps1 -PublishViewer                   — build + publish Viewer EXE (Super Admin app)
#   .\build.ps1 -PublishHostForTenant <key>      — build + publish Host EXE for one sub-admin
#   .\build.ps1 -PublishAll                      — publish Viewer + a dev Host (no LicenseKey)
#
# Full workflow when creating a new sub-admin:
#   1. In the Viewer, create the tenant and copy its LicenseKey
#   2. Run: .\build.ps1 -PublishHostForTenant <the-license-key>
#   3. Grab dist\Host\Host.exe and send it to the sub-admin
#   4. Sub-admin shares Host.exe with THEIR users; gives them AdminToken to log into Viewer
# ============================================================

param(
    [string]$PublishHostForTenant = "",   # LicenseKey for a specific sub-admin
    [switch]$PublishViewer,
    [switch]$PublishAll
)

$root    = $PSScriptRoot
$envFile = Join-Path $root ".env"

# ---- Parse .env ----
if (-not (Test-Path $envFile)) {
    Write-Error ".env file not found at $envFile"
    exit 1
}

$envVars = @{}
Get-Content $envFile | Where-Object { $_ -match "^\s*([^#=\s][^=]*)=(.*)" } | ForEach-Object {
    $key, $value = $_ -split "=", 2
    $envVars[$key.Trim()] = $value.Trim()
}

$relayUrl  = $envVars["RELAY_URL"]
$hostToken = $envVars["Auth__HostToken"]

if (-not $relayUrl)  { Write-Error "RELAY_URL is not set in .env";       exit 1 }
if (-not $hostToken) { Write-Error "Auth__HostToken is not set in .env"; exit 1 }

Write-Host ""
Write-Host "=== RemoteAdminTool Build ===" -ForegroundColor Cyan
Write-Host "  RELAY_URL  = $relayUrl"
Write-Host "  HOST_TOKEN = $($hostToken.Substring(0,[Math]::Min(6,$hostToken.Length)))..."
if ($PublishHostForTenant) {
    Write-Host "  LICENSE_KEY = $($PublishHostForTenant.Substring(0,[Math]::Min(6,$PublishHostForTenant.Length)))..."
}
Write-Host ""

# ---- [1/3] Patch Host/HostConstants.cs ----
$hostConstantsFile = Join-Path $root "Host\HostConstants.cs"
Write-Host "[1/3] Patching Host/HostConstants.cs..." -ForegroundColor Yellow

$licenseKeyValue = if ($PublishHostForTenant) { $PublishHostForTenant } else { "replace-with-license-key" }

Set-Content -Path $hostConstantsFile -Encoding UTF8 -Value @"
namespace RemoteAdminTool.Host;

/// <summary>
/// Compiled-in constants for the Host agent.
/// AUTO-GENERATED by build.ps1 — do not edit manually.
/// Run: .\build.ps1 -PublishHostForTenant <LicenseKey> to generate a sub-admin EXE.
/// </summary>
internal static class HostConstants
{
    public const string RelayUrl   = "$relayUrl";
    public const string HostToken  = "$hostToken";
    public const string LicenseKey = "$licenseKeyValue";
}
"@
Write-Host "  Done." -ForegroundColor Green

# ---- [2/3] Patch Viewer/ViewerConstants.cs ----
$viewerConstantsFile = Join-Path $root "Viewer\ViewerConstants.cs"
Write-Host "[2/3] Patching Viewer/ViewerConstants.cs..." -ForegroundColor Yellow

Set-Content -Path $viewerConstantsFile -Encoding UTF8 -Value @"
namespace RemoteAdminTool.Viewer;

/// <summary>
/// Compiled-in constants for the Viewer.
/// AUTO-GENERATED by build.ps1 — do not edit manually.
/// Edit .env and run .\build.ps1 to update.
/// </summary>
internal static class ViewerConstants
{
    public const string RelayUrl = "$relayUrl";
}
"@
Write-Host "  Done." -ForegroundColor Green

# ---- [3/3] Build solution ----
Write-Host "[3/3] Building solution..." -ForegroundColor Yellow
$buildOutput = & dotnet build "$root\RemoteAdminTool.sln" -c Release 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Host $buildOutput
    Write-Error "Build failed."
    exit 1
}
Write-Host "  Build succeeded." -ForegroundColor Green

# ---- Publish Viewer (Super Admin app) ----
if ($PublishViewer -or $PublishAll) {
    Write-Host ""
    Write-Host "Publishing Viewer (Super Admin EXE)..." -ForegroundColor Yellow
    $distViewer = Join-Path $root "Viewer\dist"
    & dotnet publish "$root\Viewer\Viewer.csproj" -c Release -r win-x64 --self-contained true `
        -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true `
        -o $distViewer 2>&1 | Where-Object { $_ -match "error|warning|published" }
    if ($LASTEXITCODE -eq 0) {
        Get-ChildItem $distViewer -Exclude "Viewer.exe" | Remove-Item -Force
        Write-Host "  Viewer EXE -> $distViewer\Viewer.exe" -ForegroundColor Green
    }
}

# ---- Publish Host for a specific sub-admin ----
if ($PublishHostForTenant) {
    Write-Host ""
    Write-Host "Publishing Host EXE for sub-admin (LicenseKey=$($PublishHostForTenant.Substring(0,6))...)..." -ForegroundColor Yellow
    $distHost = Join-Path $root "Host\dist"
    & dotnet publish "$root\Host\Host.csproj" -c Release -r win-x64 --self-contained true `
        -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true `
        -o $distHost 2>&1 | Where-Object { $_ -match "error|warning|published" }
    if ($LASTEXITCODE -eq 0) {
        # Remove PDB debug symbols and appsettings — end users only need Host.exe
        Get-ChildItem $distHost -Exclude "Host.exe" | Remove-Item -Force
        Write-Host "  Host EXE -> $distHost\Host.exe" -ForegroundColor Green
        Write-Host "     Single EXE. Send ONLY Host.exe to the sub-admin." -ForegroundColor DarkGray
    }
}

if ($PublishAll) {
    Write-Host ""
    Write-Host "Note: -PublishAll published the Viewer only." -ForegroundColor Yellow
    Write-Host "To publish a Host EXE for a sub-admin, run:" -ForegroundColor Yellow
    Write-Host "  .\build.ps1 -PublishHostForTenant <LicenseKey>" -ForegroundColor Cyan
}

Write-Host ""
Write-Host "=== Done ===" -ForegroundColor Cyan
Write-Host ""
Write-Host "Quick reference:" -ForegroundColor White
Write-Host "  Super admin logs in with:  Admin Token from .env (Auth__SuperAdminToken)"
Write-Host "  Sub-admin logs in with:    Their AdminToken (click [Details] in Viewer)"
Write-Host "  Host EXE for sub-admin:    .\build.ps1 -PublishHostForTenant <LicenseKey>"
Write-Host ""
